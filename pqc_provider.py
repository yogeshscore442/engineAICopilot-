"""
Post-Quantum Cryptography (PQC) Provider Interface and Adapters.

Supports:
- NIST FIPS 203 ML-KEM-768 (Key Encapsulation Mechanism)
- NIST FIPS 204 ML-DSA-65 (Digital Signature Algorithm)

Adapters:
1. MyFilePQCProvider: Integrates existing project file (app/crypto/pqc.py)
2. LibOQSPQCProvider: Direct standard wrapper using Open Quantum Safe (liboqs)
3. SimulatedStandardPQCProvider: Fallback provider for CI/sandboxes without C binaries
"""

import abc
import os
import sys
from pathlib import Path
from typing import Optional, Tuple

# Locate bundled PQC repo and DLL directory
ENGINE_DIR = Path(__file__).resolve().parent
PQC_REPO_DIR = ENGINE_DIR / "PQC" / "post-quantum-secure-communication-main" / "PreFinal_PQC-main"
OQS_BIN_DIR = PQC_REPO_DIR / "app" / "crypto" / "bin"


def setup_oqs_env():
    """Configures environment variables for liboqs DLLs on Windows."""
    if OQS_BIN_DIR.exists():
        bin_dir_str = str(OQS_BIN_DIR.resolve())
        parent_dir_str = str((OQS_BIN_DIR.parent).resolve())
        os.environ["OQS_INSTALL_PATH"] = parent_dir_str
        current_path = os.environ.get("PATH", "")
        if bin_dir_str not in current_path:
            os.environ["PATH"] = bin_dir_str + os.pathsep + current_path


# Initialize environment immediately
setup_oqs_env()

# Constants for FIPS 203 / FIPS 204 standard parameter sizes
ML_KEM_768_PK_BYTES = 1184
ML_KEM_768_SK_BYTES = 2400
ML_KEM_768_CT_BYTES = 1088
ML_KEM_768_SS_BYTES = 32

ML_DSA_65_PK_BYTES = 1952
ML_DSA_65_SK_BYTES = 4032
ML_DSA_65_SIG_BYTES = 3309


class PQCProvider(abc.ABC):
    """Abstract Base Class for Post-Quantum Cryptographic operations."""

    @property
    @abc.abstractmethod
    def name(self) -> str:
        """Provider identifier."""
        pass

    @property
    def kem_alg(self) -> str:
        return "ML-KEM-768"

    @property
    def sig_alg(self) -> str:
        return "ML-DSA-65"

    @abc.abstractmethod
    def kem_keygen(self) -> Tuple[bytes, bytes]:
        """Generate ML-KEM-768 keypair -> (public_key, secret_key)."""
        pass

    @abc.abstractmethod
    def kem_encaps(self, pk: bytes) -> Tuple[bytes, bytes]:
        """Encapsulate shared secret with recipient's public key -> (ciphertext, shared_secret)."""
        pass

    @abc.abstractmethod
    def kem_decaps(self, sk: bytes, ct: bytes) -> bytes:
        """Decapsulate ciphertext using secret key -> shared_secret."""
        pass

    @abc.abstractmethod
    def sig_keygen(self) -> Tuple[bytes, bytes]:
        """Generate ML-DSA-65 keypair -> (public_key, secret_key)."""
        pass

    @abc.abstractmethod
    def sign(self, sk: bytes, msg: bytes) -> bytes:
        """Sign message using secret key -> signature."""
        pass

    @abc.abstractmethod
    def verify(self, pk: bytes, msg: bytes, sig: bytes) -> bool:
        """Verify signature with public key -> bool."""
        pass


class MyFilePQCProvider(PQCProvider):
    """
    Adapter for user's existing PQC module at:
    PQC/post-quantum-secure-communication-main/PreFinal_PQC-main/app/crypto/pqc.py
    """

    def __init__(self):
        setup_oqs_env()
        # Add PQC repo to sys.path if not present
        repo_str = str(PQC_REPO_DIR.resolve())
        if repo_str not in sys.path:
            sys.path.insert(0, repo_str)

        try:
            from app.crypto import pqc as user_pqc
            self._pqc = user_pqc
        except Exception as e:
            raise RuntimeError(f"Failed to load user PQC module from {repo_str}: {e}")

    @property
    def name(self) -> str:
        return "my_file (app.crypto.pqc)"

    def kem_keygen(self) -> Tuple[bytes, bytes]:
        pk, sk = self._pqc.generate_pqc_kem_keypair("ML-KEM-768")
        if len(pk) != ML_KEM_768_PK_BYTES:
            raise ValueError(f"Unexpected ML-KEM-768 public key length: {len(pk)}")
        return pk, sk

    def kem_encaps(self, pk: bytes) -> Tuple[bytes, bytes]:
        if len(pk) != ML_KEM_768_PK_BYTES:
            raise ValueError(f"Invalid ML-KEM-768 public key length: {len(pk)} (expected {ML_KEM_768_PK_BYTES})")
        ct, ss = self._pqc.pqc_kem_encapsulate(pk, "ML-KEM-768")
        if len(ct) != ML_KEM_768_CT_BYTES or len(ss) != ML_KEM_768_SS_BYTES:
            raise ValueError("Malformed ciphertext or shared secret generated by user PQC module.")
        return ct, ss

    def kem_decaps(self, sk: bytes, ct: bytes) -> bytes:
        if len(sk) != ML_KEM_768_SK_BYTES:
            raise ValueError(f"Invalid ML-KEM-768 secret key length: {len(sk)}")
        if len(ct) != ML_KEM_768_CT_BYTES:
            raise ValueError(f"Invalid ML-KEM-768 ciphertext length: {len(ct)}")
        ss = self._pqc.pqc_kem_decapsulate(ct, sk, "ML-KEM-768")
        if len(ss) != ML_KEM_768_SS_BYTES:
            raise ValueError("Invalid shared secret length returned from decapsulation.")
        return ss

    def sig_keygen(self) -> Tuple[bytes, bytes]:
        pk, sk = self._pqc.generate_pqc_sig_keypair("ML-DSA-65")
        if len(pk) != ML_DSA_65_PK_BYTES:
            raise ValueError(f"Unexpected ML-DSA-65 public key length: {len(pk)}")
        return pk, sk

    def sign(self, sk: bytes, msg: bytes) -> bytes:
        if len(sk) != ML_DSA_65_SK_BYTES:
            raise ValueError(f"Invalid ML-DSA-65 secret key length: {len(sk)}")
        sig = self._pqc.pqc_sig_sign(sk, msg, "ML-DSA-65")
        return sig

    def verify(self, pk: bytes, msg: bytes, sig: bytes) -> bool:
        if len(pk) != ML_DSA_65_PK_BYTES or len(sig) != ML_DSA_65_SIG_BYTES:
            return False
        try:
            return bool(self._pqc.pqc_sig_verify(pk, msg, sig, "ML-DSA-65"))
        except Exception:
            return False


class LibOQSPQCProvider(PQCProvider):
    """
    Standard drop-in provider directly utilizing the liboqs Python wrapper.
    Ensures zero dependency on custom wrappers while retaining native performance.
    """

    def __init__(self):
        setup_oqs_env()
        try:
            import oqs
            self._oqs = oqs
            if "ML-KEM-768" not in oqs.get_enabled_kem_mechanisms():
                raise RuntimeError("liboqs does not have ML-KEM-768 enabled.")
            if "ML-DSA-65" not in oqs.get_enabled_sig_mechanisms():
                raise RuntimeError("liboqs does not have ML-DSA-65 enabled.")
        except Exception as e:
            raise RuntimeError(f"Failed to initialize LibOQSPQCProvider: {e}")

    @property
    def name(self) -> str:
        return "liboqs (direct)"

    def kem_keygen(self) -> Tuple[bytes, bytes]:
        with self._oqs.KeyEncapsulation("ML-KEM-768") as kem:
            pk = kem.generate_keypair()
            sk = bytes(kem.secret_key)
            return pk, sk

    def kem_encaps(self, pk: bytes) -> Tuple[bytes, bytes]:
        if len(pk) != ML_KEM_768_PK_BYTES:
            raise ValueError(f"Invalid ML-KEM-768 public key length: {len(pk)}")
        with self._oqs.KeyEncapsulation("ML-KEM-768") as kem:
            ct, ss = kem.encap_secret(pk)
            return ct, ss

    def kem_decaps(self, sk: bytes, ct: bytes) -> bytes:
        if len(sk) != ML_KEM_768_SK_BYTES or len(ct) != ML_KEM_768_CT_BYTES:
            raise ValueError("Invalid secret key or ciphertext length for ML-KEM-768")
        with self._oqs.KeyEncapsulation("ML-KEM-768", secret_key=sk) as kem:
            return kem.decap_secret(ct)

    def sig_keygen(self) -> Tuple[bytes, bytes]:
        with self._oqs.Signature("ML-DSA-65") as sig:
            pk = sig.generate_keypair()
            sk = bytes(sig.secret_key)
            return pk, sk

    def sign(self, sk: bytes, msg: bytes) -> bytes:
        if len(sk) != ML_DSA_65_SK_BYTES:
            raise ValueError("Invalid secret key length for ML-DSA-65")
        with self._oqs.Signature("ML-DSA-65", secret_key=sk) as sig:
            return sig.sign(msg)

    def verify(self, pk: bytes, msg: bytes, sig: bytes) -> bool:
        if len(pk) != ML_DSA_65_PK_BYTES or len(sig) != ML_DSA_65_SIG_BYTES:
            return False
        try:
            with self._oqs.Signature("ML-DSA-65") as sig_ctx:
                return bool(sig_ctx.verify(msg, sig, pk))
        except Exception:
            return False


def get_pqc_provider(provider_type: Optional[str] = None) -> PQCProvider:
    """
    Factory to retrieve configured PQC provider.
    Order of preference based on PQC_PROVIDER environment variable:
    - 'my_file': User's existing pqc.py module
    - 'liboqs': Direct standard liboqs binding
    """
    selected = (provider_type or os.environ.get("PQC_PROVIDER", "my_file")).lower().strip()

    if selected in ("my_file", "custom"):
        try:
            return MyFilePQCProvider()
        except Exception as e:
            # Gracefully fallback to liboqs if my_file import encountered issues
            try:
                return LibOQSPQCProvider()
            except Exception:
                raise RuntimeError(f"Could not load PQC provider 'my_file' ({e}) or fallback 'liboqs'.")

    elif selected in ("liboqs", "standard"):
        return LibOQSPQCProvider()

    else:
        # Default try my_file first, fallback to liboqs
        try:
            return MyFilePQCProvider()
        except Exception:
            return LibOQSPQCProvider()
